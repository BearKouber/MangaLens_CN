/**
 * The interface in Simplified Chinese when the phone is set to Chinese,
 * English otherwise. The key is the English copy exactly as the call site
 * writes it, so the English stays the source of truth and its tests are
 * untouched; a line missing from the table simply shows in English.
 * Templates take their values as [args], `%s` and `%d` as String.format.
 */
// One table, Simplified only; Traditional readers get Simplified. Move to strings.xml if more languages come.
internal fun tr(en: String, vararg args: Any?): String {
    val text = if (Locale.getDefault().language == "zh") ZH[en] ?: en else en
    return if (args.isEmpty()) text else String.format(Locale.ROOT, text, *args)
